export function getStartingPistol(team: Team): WeaponId {
  return team === 'CT' ? 'usp' : 'glock';
}

export function getBuyableWeaponsByCategory(
  category: Exclude<WeaponCategory, 'melee'>,
  team: Team
): WeaponSpec[] {
  return Object.values(WEAPONS_DB).filter(
    (w) =>
      w.category === category &&
      w.price > 0 &&
      (w.team === 'BOTH' || w.team === team)
  );
}
