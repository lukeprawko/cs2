export type Team = 'CT' | 'T';

export type WeaponCategory =
  | 'pistol'
  | 'smg'
  | 'rifle'
  | 'heavy'
  | 'melee'
  | 'grenade';

export type WeaponSlot = 1 | 2 | 3 | 4 | 5; // 1: Primary, 2: Secondary, 3: Knife, 4: Grenade, 5: C4 Bomb

export type WeaponId =
  | 'glock'
  | 'usp'
  | 'p250'
  | 'deagle'
  | 'cz75'
  | 'mp9'
  | 'mac10'
  | 'ump45'
  | 'galil'
  | 'famas'
  | 'ak47'
  | 'm4a1s'
  | 'aug'
  | 'ssg08'
  | 'nova'
  | 'awp'
  | 'knife'
  | 'he_grenade'
  | 'flashbang'
  | 'smoke_grenade'
  | 'c4';

export interface WeaponSpec {
  id: WeaponId;
  name: string;
  shortName: string;
  category: WeaponCategory;
  slot: WeaponSlot;
  team: Team | 'BOTH';
  price: number;
  killReward: number;
  damage: number;
  armorPenetration: number; // 0.0 - 1.0 (fraction of damage that bypasses armor)
  wallPenetration: number; // max thin wall thickness in meters it can pierce
  fireRate: number; // rounds per minute
  automatic: boolean;
  canSpamHold?: boolean; // allows rapid semi-auto spam when rapidly clicking or holding
  pellets: number; // >1 for shotguns
  magSize: number;
  reserveAmmo: number;
  reloadTime: number; // seconds
  deployTime: number; // seconds
  moveSpeed: number; // m/s (base knife is 5.2 m/s)
  baseSpread: number; // radians when standing still
  crouchSpreadMult: number;
  moveSpreadBonus: number; // extra radians at full move speed
  jumpSpreadBonus: number; // extra radians while airborne
  spamSpreadPerShot: number; // extra bloom per rapid shot when spamming
  recoilVertical: number; // radians per shot
  recoilHorizontal: number; // radians per shot
  recoilRecoveryRate: number; // radians/sec reset speed
  zoomLevels?: number[]; // FOV values when scoped (e.g. [40] or [32, 12])
  scopedSpreadMult?: number;
  range: number; // max effective distance in meters
  hotkey?: string;
}

